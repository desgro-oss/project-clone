/* ============================================================
   TransferRateHistoryModal.demo.js — сценарий демо витрины для окна
   «История изменения ставок». Пишется руками; страницу рядом собирает
   kit-build.mjs и подключает этот файл последним.

   Окно — справка: правки нет, строки читает из стора на каждом открытии,
   витрине стор не нужен — load() принимает строки аргументом (для витрины,
   как сказано в API окна). Без сценария на витрине таблица пуста; сценарий
   подставляет строки из fixtures.json функцией самого окна:
   - «Есть данные» — четыре строки, от новых к старым;
   - «Часть ставок не посчитана» — в ячейке «—» (пустая ставка всегда внизу);
   - «Нет данных» — строк нет, пагинации нет;
   - «Длинные значения» — самая длинная запись ставки;
   - «Много строк» — 800 строк, 16 страниц по 50: сортировку шапки и
     пагинацию ведёт само окно.
   На страницах этот файл не подключается — там окно открывает страница.
   ============================================================ */
(function () {
  'use strict';

  var LABELS = {
    data: 'Есть данные',
    partial: 'Часть ставок не посчитана',
    empty: 'Нет данных',
    long: 'Длинные значения',
    many: 'Много строк (пагинация)'
  };

  window.IBPKitDemo.register('TransferRateHistoryModal', {
    states: ['data', 'partial', 'empty', 'long', 'many'],
    labels: LABELS,
    controls: function (defs) {
      defs.forEach(function (d) { if (d.key === 'state') d.value = 'data'; });
      return defs;
    },
    apply: function (scrim, st, ctx) {
      var M = window.PostModalTransferRateHistory;
      var f = (ctx.fixtures || {})[st.state];
      if (!M || !f) return;
      var api = M.bind(scrim);
      if (!api) return;
      api.load(f.rows || []);
    }
  });
})();
